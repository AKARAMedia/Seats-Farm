-- Image registry: one row per file in the public Storage bucket "images".
-- Run this once in the Supabase SQL Editor. Safe to re-run.

create table if not exists public.images (
  id bigint generated always as identity primary key,
  filename text not null unique,          -- object name in the "images" bucket
  alt text,                               -- default alt text for the image
  size_bytes bigint,
  content_type text,
  created_at timestamptz not null default now()
);

alter table public.images enable row level security;

-- Anyone (the website) can read; only the secret key / dashboard can write.
drop policy if exists "Public can read images" on public.images;
create policy "Public can read images" on public.images
  for select to anon, authenticated using (true);

